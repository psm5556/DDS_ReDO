def apply_api_docs(app: FastAPI) -> None:
    for r in app.routes:
        if isinstance(r, APIRoute) and r.name in DOCS:
            tag, summary, desc = DOCS[r.name]
            r.tags = [tag]
            r.summary = summary
            r.description = desc + (f"\n\n{r.description}" if r.description and r.description not in desc else "")
    app.openapi_schema = None  # 다시 만들도록
